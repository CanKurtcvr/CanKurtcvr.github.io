const TIERS: RarityTier[] = ["Common", "Rare", "Epic", "Legendary"];

function stages(
  names: [string, string, string, string],
  titles: [string, string, string, string],
  lore: string,
  glow: string,
): GearUpgradeStage[] {
  return names.map((name, i) => ({
    tier: TIERS[i] as RarityTier,
    name,
    title: titles[i] as string,
    statBoost: [4, 9, 16, 26][i] as number,
    visualGlow: glow,
    lore,
  }));
}

function gear(config: {
  id: string;
  slot: GearSlot;
  islandOrigin: IslandId;
  statName: GearItem["statBonus"]["statName"];
  description: string;
  lore: string;
  icon: string;
  visualColor: string;
  names: [string, string, string, string];
  titles: [string, string, string, string];
}): GearItem {
  const stageList = stages(config.names, config.titles, config.lore, config.visualColor);
  return {
    id: config.id,
    slot: config.slot,
    name: config.names[0],
    tier: "Common",
    level: 1,
    description: config.description,
    lore: config.lore,
    islandOrigin: config.islandOrigin,
    statBonus: { statName: config.statName, amount: 4 },
    icon: config.icon,
    visualColor: config.visualColor,
    streakRequirementForNext: 7,
    unlocked: true,
    stages: stageList,
  };
}

